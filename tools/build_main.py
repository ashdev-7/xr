"""Generate the standalone src/main.py from src/stages/*.py.

The FAQ requires a standalone Python script (main.py). Parsing the whole estimator as one file costs ~7 MB of
traced heap (7.9 MB peak on Python 3.13 when traced from interpreter start), so main.py carries each stage as an
embedded raw string and compiles the stages one at a time (<= ~2 MB each). The readable source is src/stages/;
the section of main.py between the BEGIN/END markers is generated here and must not be edited by hand.

usage: python tools/build_main.py           rewrite src/main.py
       python tools/build_main.py --check   exit 1 if src/main.py is out of date (used by tests/test_build.py)
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MAIN = os.path.join(ROOT, "src", "main.py")
STAGE_DIR = os.path.join(ROOT, "src", "stages")
ORDER = ("pg_ingest", "pg_math", "pg_attitude", "pg_translation", "pg_output")
BEGIN = "# ----------------------------------------------------------------------------- BEGIN EMBEDDED STAGES"
END = "# ----------------------------------------------------------------------------- END EMBEDDED STAGES"

HEAD = '''# Generated by tools/build_main.py from src/stages/*.py -- do not edit this section; edit the stage files.
# The pipeline is embedded as five stage texts and compiled one at a time into this module's namespace, so the
# code behaves exactly as one file while the transient parsing cost stays small (parsing all ~1,100 lines at
# once costs ~7 MB of heap; one stage at a time <= ~2 MB). Tracebacks name the stage file and its line.
'''

TAIL = '''

def _load_stages():
    g = globals()
    for name, text in _STAGES:
        code = compile(text, "src/stages/" + name + ".py", "exec")
        exec(code, g)
        del code


try:
    _load_stages()
    LOAD_ERROR = None
except Exception as _e:  # noqa: BLE001  (any failure -> stand-still output, never a crash)
    LOAD_ERROR = f"{type(_e).__name__}: {_e}"
'''


def section():
    parts = [BEGIN, HEAD, "_STAGES = ("]
    for name in ORDER:
        text = open(os.path.join(STAGE_DIR, name + ".py"), encoding="utf-8").read()
        assert "'''" not in text and not text.endswith("\\"), name
        parts.append(f"    ({name!r}, r'''{text}'''),")
    parts.append(")")
    return "\n".join(parts) + TAIL + END


def build(s):
    if BEGIN in s:
        a, b = s.index(BEGIN), s.index(END) + len(END)
    else:  # first build: replace the file-based loader written by tools/split_main.py
        a = s.index("# ----------------------------------------------------------------------------- stage loader")
        k = s.index('    LOAD_ERROR = f"{type(_e).__name__}: {_e}"')
        b = k + len('    LOAD_ERROR = f"{type(_e).__name__}: {_e}"')
    return s[:a] + section() + s[b:]


if __name__ == "__main__":
    cur = open(MAIN, encoding="utf-8").read()
    new = build(cur)
    if "--check" in sys.argv:
        if new != cur:
            sys.exit("src/main.py is out of date: run python tools/build_main.py")
        print("src/main.py is up to date")
    else:
        open(MAIN, "w", encoding="utf-8", newline="\n").write(new)
        print("wrote src/main.py:", new.count("\n") + 1, "lines")
